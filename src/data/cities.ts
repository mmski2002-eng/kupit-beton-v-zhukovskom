function normalizeCityGeoClaims(value: string): string {
  return value
    .replace(/Завод — прямо в вашем городе\./g, 'Доставляем бетон в ваш город.')
    .replace(/Завод работает в Жуковском с 2003 года\./g, 'Поставки в Жуковский идут с 2003 года.')
    .replace(/Завод работает в Жуковском\./g, 'Поставка в Жуковский идёт напрямую.')
    .replace(/Завод ООО «ПСК «Прогресс» работает в Жуковском/g, 'ООО «ПСК «Прогресс» доставляет бетон в Жуковский')
    .replace(/Наш завод работает в Жуковском/g, 'Поставка идёт с ближайшей производственной площадки')
    .replace(/Бетон в ([^:—]+?) от завода в Жуковском/g, 'Бетон в $1 от производителя')
    .replace(/от завода в Жуковском/g, 'от производителя')
    .replace(/с завода в Жуковском/g, 'с производственной площадки')
    .replace(/завод в Жуковском/gi, 'производитель')
    .replace(/завода в Жуковском/gi, 'производственной площадки')
    .replace(/~(\d+) км от завода в Жуковском/g, '~$1 км от производственной площадки')
    .replace(/В Жуковском мы с 2003 года/g, 'Работаем по Жуковскому с 2003 года')
    .replace(/работает в городе с 2003 года/g, 'поставляет бетон в город с 2003 года')
    .replace(/бетонный завод с 2003 года в соседнем Жуковском/g, 'производитель бетона с 2003 года')
    .replace(/завод работает с 2003 года и находится всего в 9 км, в Жуковском/g, 'производитель работает с 2003 года, маршрут до Кратово занимает около 9 км')
    .replace(/Жуковский — наш родной город и основная зона работы/g, 'Жуковский — основная зона доставки')
    .replace(/работаем на своей территории/g, 'работаем по своей зоне доставки');
}

function normalizeCityData<T>(value: T): T {
  if (typeof value === 'string') return normalizeCityGeoClaims(value) as T;
  if (Array.isArray(value)) return value.map(normalizeCityData) as T;
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, normalizeCityData(item)])) as T;
  }
  return value;
}

